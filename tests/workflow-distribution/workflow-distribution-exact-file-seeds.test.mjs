import assert from 'node:assert/strict';
import {mkdir, readFile, writeFile} from 'node:fs/promises';
import {dirname, join} from 'node:path';
import test from 'node:test';

import {createTemporaryDirectory} from '../helpers/cleanup.mjs';
import {syncWorkflowDistribution} from '../../lib/workflow-distribution/workflow-distribution-sync.mjs';
import {buildWorkflowDistribution, repositoryOwnedSeedPaths} from '../../lib/workflow-distribution/workflow-distribution.mjs';

const distributionConfig = {
    distributedSkills: ['review'],
    sourceOnlySkills: [],
    repositoryOwnedSeeds: ['.arwignore', '.custom', 'docs/licenses/arw/', 'docs/licenses/arw/LOCAL.txt'],
};

const projectionConfig = {
    source: 'codex',
    skills: {root: 'skills/', additionalSkillReferences: []},
    platforms: {
        codex: {
            supportedVersionRange: '*',
            format: {skillReference: '${name}', excludedSkillPaths: []},
            targets: {skills: '.agents/skills/', configuration: '.codex/config.toml'},
        },
        'claude-code': {
            supportedVersionRange: '*',
            format: {skillReference: '/{name}', excludedSkillPaths: ['agents/openai.yaml']},
            targets: {skills: '.claude/skills/'},
        },
    },
};

const write = async (/** @type {string} */ root, /** @type {string} */ path, /** @type {string | NodeJS.ArrayBufferView<ArrayBufferLike> | Iterable<string | NodeJS.ArrayBufferView<ArrayBufferLike>> | AsyncIterable<string | NodeJS.ArrayBufferView<ArrayBufferLike>>} */ contents) => {
    const target = join(root, ...path.split('/'));
    await mkdir(dirname(target), {recursive: true});
    await writeFile(target, contents);
};

const createSourceCheckout = async (/** @type {test.TestContext} */ t) => {
    const root = await createTemporaryDirectory(t, 'arw-sync-exact-seed-');
    await write(root, 'AGENTS.md', '<!-- arw:managed:start -->\nManaged root.\n<!-- arw:managed:end -->\n');
    await write(root, 'docs/agents/writing.md', '<!-- arw:managed:start -->\nManaged writing.\n<!-- arw:managed:end -->\n');
    await write(root, 'docs/agents/roles/reviewer.md', '# Reviewer\n');
    await write(root, 'docs/licenses/arw/LICENSE.example-source', 'License.\n');
    await write(root, '.agents/skills/review/SKILL.md', 'Use $review and $external now.\n');
    await write(root, '.agents/skills/review/agents/openai.yaml', 'interface:\n  display_name: Review\n');
    await write(root, 'distribution/config.json', `${JSON.stringify(distributionConfig, null, 2)}\n`);
    await write(root, 'distribution/projections/config.json', `${JSON.stringify(projectionConfig, null, 2)}\n`);
    await write(root, 'distribution/projections/codex/config.toml', 'include_collaboration_mode_instructions = false\n');
    await write(root, 'distribution/baseline/.arwignore', '.tmp/\n');
    await write(root, 'distribution/baseline/.custom', 'repository seed bytes\n');
    await write(root, 'distribution/baseline/docs/licenses/arw/LOCAL.txt', 'independent seed bytes\n');
    await write(root, 'distribution/baseline/docs/licenses/arw/LICENSE.example-source', 'stale generated bytes\n');
    await write(root, 'distribution/baseline/obsolete.md', 'delete me\n');
    return root;
};

/** @type {NonNullable<Parameters<typeof syncWorkflowDistribution>[0]['stateAdapter']>} */
const cleanState = {
    async inspect(/** @type {string[]} */ paths) {
        return {diagnostics: [], status: 'succeeded'};
    },
};

test('sync preserves every configured exact file seed and deletes only obsolete generated baseline files', async t => {
    const repositoryRoot = await createSourceCheckout(t);
    const result = await syncWorkflowDistribution({repositoryRoot, stateAdapter: cleanState});
    assert.equal(result.status, 'succeeded', JSON.stringify(result.diagnostics));
    assert.equal(
        await readFile(join(repositoryRoot, 'distribution', 'baseline', '.custom'), 'utf8'),
        'repository seed bytes\n',
    );
    assert.equal(
        await readFile(join(repositoryRoot, 'distribution', 'baseline', 'docs', 'licenses', 'arw', 'LOCAL.txt'), 'utf8'),
        'independent seed bytes\n',
    );
    assert.equal(
        await readFile(join(repositoryRoot, 'distribution', 'baseline', 'docs', 'licenses', 'arw', 'LICENSE.example-source'), 'utf8'),
        'License.\n',
    );
    const rebuilt = await buildWorkflowDistribution({distributionDirectory: join(repositoryRoot, 'distribution')});
    assert.equal(rebuilt.status, 'succeeded', JSON.stringify(rebuilt.diagnostics));
    if (rebuilt.status !== 'succeeded') throw new Error('Expected a rebuilt Workflow Distribution.');
    assert.deepEqual(repositoryOwnedSeedPaths({distributionConfig: rebuilt.distributionConfig, payload: rebuilt.payload}), [
        '.arwignore', '.custom', 'docs/licenses/arw/LICENSE.example-source', 'docs/licenses/arw/LOCAL.txt',
    ]);
    await assert.rejects(
        readFile(join(repositoryRoot, 'distribution', 'baseline', 'obsolete.md')),
        {code: 'ENOENT'},
    );
});

test('a directory seed without a projected baseline file fails before sync deletes anything', async t => {
    const repositoryRoot = await createSourceCheckout(t);
    await write(repositoryRoot, 'distribution/config.json', `${JSON.stringify({...distributionConfig, repositoryOwnedSeeds: ['.arwignore', 'missing/']})}\n`);
    const result = await syncWorkflowDistribution({repositoryRoot, stateAdapter: cleanState});
    assert.equal(result.status, 'blocked');
    assert.deepEqual(result.diagnostics, [{
        code: 'repository-seed-source-missing',
        message: 'A repository-owned seed directory has no baseline files.',
        path: 'missing/',
    }]);
    assert.equal(await readFile(join(repositoryRoot, 'distribution', 'baseline', 'obsolete.md'), 'utf8'), 'delete me\n');
});
